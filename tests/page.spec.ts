import { expect, test } from '@playwright/test'
import { readFileSync } from 'node:fs'

test('完整稿件、九组图表与主要交互', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', (error) => { errors.push(error.message); console.error(error.stack) })
  await page.goto('/')
  await expect(page.locator('figure')).toHaveCount(9)
  await expect(page.locator('figure').filter({ has: page.locator('canvas') })).toHaveCount(6)
  await expect(page.locator('#figure-07 h3')).toHaveText('三条治理路径')
  await expect(page.locator('#figure-07 table tbody tr')).toHaveCount(4)
  await expect(page.locator('#figure-07 + .body-paragraph')).toContainText('从中国、美国和欧盟的治理路径来看，三者各有侧重。')
  const manuscript = readFileSync('原始稿件/综述稿.md', 'utf8').replace(/\r/g, '').split('\n# 资料来源')[0]
  const paragraphCount = manuscript.split(/^## /m).slice(1).flatMap((section) => section.slice(section.indexOf('\n')).trim().split(/\n\s*\n/)).length
  await expect(page.locator('.body-paragraph')).toHaveCount(paragraphCount)
  await expect(page.locator('.figure-tools, .data-table, #chart-index, .source-search, .data-downloads, blockquote, .section-deck, .reading-mode, .expand-text')).toHaveCount(0)
  await expect(page.locator('.citation, .reference-list, #sources, .reading-progress, .figure-sources')).toHaveCount(0)
  await expect(page.getByText('自主网络能力，进步得有多快？')).toHaveCount(0)
  for (const paragraph of await page.locator('.body-paragraph').allTextContents()) expect(paragraph).not.toMatch(/\[\d+\]/)
  await expect(page.getByRole('button', { name: /CSV|PNG|^数据$/ })).toHaveCount(0)
  await page.screenshot({ path: 'artifacts/desktop.png' })

  const disclosure = page.locator('#figure-03')
  const safety = JSON.parse(readFileSync('public/data/safety-assessments.json', 'utf8'))
  await expect(disclosure.locator('h3')).toHaveText('九品牌模型的公开安全评估')
  await expect(disclosure.locator('.stat-strip strong').first()).toHaveText(String(safety.records.length))
  await expect(disclosure).not.toContainText('857')
  expect(safety.brands).toEqual(['OpenAI', 'Anthropic', 'Meta', 'Grok', 'Gemini', 'DeepSeek', 'Kimi', 'Qwen', 'GLM'])
  expect(new Set(safety.records.map((record: { url: string }) => record.url)).size).toBe(safety.records.length)
  for (const year of safety.years) {
    await disclosure.getByRole('button', { name: year + ' 年', exact: true }).click()
    const count = safety.records.filter((record: { date: string }) => record.date.startsWith(String(year))).length
    await expect(disclosure.locator('.stat-strip strong').first()).toHaveText(String(count))
    await expect(disclosure.getByRole('button', { name: year + ' 年', exact: true })).toHaveAttribute('aria-pressed', 'true')
  }
  await disclosure.getByRole('button', { name: '全部年份' }).click()
  await disclosure.screenshot({ path: 'artifacts/safety-assessments.png' })

  const pace = page.locator('#figure-04')
  await pace.locator('select').selectOption('18—34岁')
  await expect(pace.locator('.pace-legend')).toContainText('暂停研发 42%')
  await expect(pace.locator('.pace-legend')).toContainText('放慢研发 43%')
  await expect(pace.locator('.chart-takeaway')).toHaveCount(0)

  const opinion = page.locator('#figure-05')
  await opinion.getByRole('button', { name: '跨国监管信任' }).click()
  await opinion.getByLabel('全部 30 国').check()
  await expect(opinion.locator('canvas')).toBeVisible()
  await expect(opinion.locator('.figure-note')).toContainText('原报告未覆盖中国')

  const policy = page.locator('#figure-06')
  await expect(policy.locator('canvas')).toBeVisible()
  await expect(page.locator('.policy-body [data-policy]')).toHaveCount(15)
  await expect(page.locator('.policy-body a[title*="S.5576"]')).toHaveAttribute('title', /提案/)
  await expect(page.locator('.policy-body a[title*="通用 AI 实践准则"]')).toHaveAttribute('title', /自愿准则/)
  await expect(page.locator('.policy-body')).toContainText('2027年12月2日')
  await expect(page.locator('.policy-body')).toContainText('2028年8月2日')
  const policyBody = await page.locator('.policy-body').boundingBox()
  const policyTimeline = await page.locator('.policy-timeline').boundingBox()
  expect(policyTimeline!.x - policyBody!.x - policyBody!.width).toBe(40)
  expect(policyTimeline!.y).toBeCloseTo(policyBody!.y, 0)

  const companies = page.locator('#figure-02')
  await expect(companies.locator('select, canvas')).toHaveCount(0)
  await expect(companies.locator('.matrix-cell')).toHaveCount(24)
  const evidenceDialog = page.getByRole('dialog', { name: '相关证据' })
  await companies.locator('.matrix-cell').nth(13).hover()
  await expect(evidenceDialog).not.toBeVisible()
  await companies.locator('.matrix-cell').nth(13).click()
  await expect(evidenceDialog).toBeVisible()
  await expect(evidenceDialog.locator('.detail-tag')).toHaveText('资料不足')
  await evidenceDialog.getByRole('button', { name: '关闭相关证据' }).click()
  await expect(evidenceDialog).not.toBeVisible()
  await companies.locator('.matrix-cell').first().focus()
  await page.keyboard.press('Enter')
  await expect(evidenceDialog).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(evidenceDialog).not.toBeVisible()
  await expect(companies.locator('.matrix-cell').first()).toBeFocused()
  await expect(page.locator('.company-logo img')).toHaveCount(4)
  expect(await page.locator('.company-logo img').evaluateAll(images => images.every(image => (image as HTMLImageElement).naturalWidth > 0))).toBe(true)
  expect(await page.locator('.sidebar').evaluate(el => getComputedStyle(el).width)).toBe('230px')
  await expect(page.locator('.sidebar nav a').first()).toHaveCSS('font-weight', '700')
  await companies.screenshot({ path: 'artifacts/company-matrix.png' })
  const defense = page.locator('#figure-09')
  await defense.getByRole('button', { name: '外部治理' }).click()
  await expect(defense.locator('.evidence-detail h4')).toHaveText('谁来监督并承担责任？')

  const timeline = page.locator('#figure-01')
  await expect(timeline.locator('select')).toHaveCount(0)
  const firstDate = await page.locator('[data-event="0"]').boundingBox()
  const chartBox = await timeline.locator('.echart').boundingBox()
  await timeline.locator('.echart').click({ position: { x: 12, y: firstDate!.y + firstDate!.height / 2 - chartBox!.y } })
  await expect(timeline.locator('.evidence-detail')).toHaveCount(0)
  const bodyBox = await page.locator('.section-1 .incident-body').boundingBox()
  const timelineBox = await page.locator('.section-1 .incident-timeline').boundingBox()
  expect(bodyBox!.width).toBe(700)
  expect(timelineBox!.x - bodyBox!.x - bodyBox!.width).toBe(40)
  expect(timelineBox!.y).toBeCloseTo(bodyBox!.y, 0)
  await page.getByRole('navigation').locator('a[href="#incidents"]').click()
  await expect.poll(() => page.locator('#incidents').evaluate(el => Math.round(el.getBoundingClientRect().top))).toBe(96)
  await page.screenshot({ path: 'artifacts/incidents.png' })
  await expect(page.locator('.section-1 .date-highlight')).toHaveCount(10)
  expect(await page.locator('.article-wrap').evaluate(el => el.getBoundingClientRect().width)).toBe(900)
  await expect.poll(() => page.evaluate(() => {
    const canvas = document.querySelector<HTMLCanvasElement>('#figure-01 canvas')!
    const bounds = canvas.getBoundingClientRect()
    const scale = canvas.width / bounds.width
    return [...document.querySelectorAll<HTMLElement>('[data-event]')].every(date => {
      const box = date.getBoundingClientRect()
      const pixel = canvas.getContext('2d')!.getImageData(Math.round(12 * scale), Math.round((box.top + box.height / 2 - bounds.top) * scale), 1, 1).data
      return getComputedStyle(date).color === 'rgb(' + [...pixel].slice(0, 3).join(', ') + ')'
    })
  })).toBe(true)
  expect(errors).toEqual([])
})
